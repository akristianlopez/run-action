package webapi

import (
	"fmt"
	"strings"
)

func mInit(key string) (string, error) {
	//create table role
	switch strings.ToLower(key) {
	case "role":
		return `CREATE OBJECT ROLE(CODE VARCHAR(5) NOT NULL PRIMARY KEY, NAME VARCHAR(25) NOT NULL)`, nil
	case "process":
		return `CREATE OBJECT PROCESS(CODE VARCHAR(6) NOT NULL, ROLE VARCHAR(5) NOT NULL, NAME VARCHAR(25) NOT NULL, ID NUMBER(12) NOT NULL DEFAULT 0, PRIMARY KEY(CODE), FOREIGN KEY(ROLE)REFERENCES ROLE(CODE))`, nil
	case "knowledge":
		return `CREATE OBJECT KNOWLEDGE(GOAL VARCHAR(250) NOT NULL, PROC VARCHAR(6) NOT NULL,LEVEL NUMBER(1) NOT NULL DEFAULT 1, ID  NUMBER(12) NOT NULL DEFAULT 0,	PRIMARY KEY(GOAL, PROC), FOREIGN KEY(PROC)REFERENCES PROCESS(CODE))
				CREATE OBJECT TRANSACTION(NAME VARCHAR(25) NOT NULL PRIMARY, ID  NUMBER(12) NOT NULL DEFAULT 0)
				CREATE OBJECT CONTEXT(GOAL VARCHAR(250) NOT NULL, PROC VARCHAR(6) NOT NULL, OBJECT VARCHAR(25) NOT NULL, TRANS VARCHAR(25) NOT NULL, PRIMARY KEY(GOAL, PROC, OBJECT,TRANS,ID  NUMBER(12) NOT NULL DEFAULT 0), FOREIGN KEY(GOAL,PROC)REFERENCES KNOWLEDGE(GOAL,PROC), FOREIGN KEY(TRANS) REFERENCES TRANSACTION(NAME))
				CREATE OBJECT RULE(GOAL VARCHAR(250) NOT NULL, PROC VARCHAR(6) NOT NULL,ACTION TEXT NOT NULL, SCREEN TEXT NOT NULL, PRIMARY KEY(GOAL,PROC),FOREIGN KEY(GOAL,PROC)REFERENCES KNOWLEDGE(GOAL,PROC))
				CREATE OBJECT FILTER(GOAL VARCHAR(250) NOT NULL, PROC VARCHAR(6) NOT NULL, OBJECT VARCHAR(25) NOT NULL, FILTER VARCHAR(500) NOT NULL, PRIMARY KEY(GOAL,PROC,OBJECT),FOREIGN KEY(GOAL,PROC)REFERENCES KNOWLEDGE(GOAL,PROC))`, nil
	case "labels":
		return `CREATE OBJECT IDS(PROC VARCHAR(6) NOT NULL,ID NUMBER(12) NOT NULL, PRIMARY KEY(PROC,ID),FOREIGN KEY(PROC)REFERENCES PROCESS(CODE))
				CREATE OBJECT LAN(CODE VARCHAR(4) NOT NULL, LABEL VARCHAR(25) NOT NULL, ID NUMBER(12) NOT NULL DEFAULT 0, PRIMARY KEY(CODE))
				CREATE OBJECT TEXT(ID NUMBER(12) NOT NULL, PROC VARCHAR(6) NOT NULL, LAN VARCHAR(05) NOT NULL, Text VARCHAR(1000) NOT NULL, PRIMARY KEY(ID, PROC, LAN), FOREIGN KEY(PROC)REFERENCES PROCESS(CODE), FOREIGN KEY(LAN)REFERENCES LAN(CODE))`, nil
	case "contract":
		return `CREATE OBJECT CONTRACT(NAME VARCHAR(50) NOT NULL, PROC VARCHAR(6) NOT NULL, GOAL VARCHAR(250) NOT NULL, PRIMARY KEY(NAME),FOREIGN KEY(GOAL,PROC)REFERENCES KNOWLEDGE(GOAL,PROC))`, nil
	default:
		return "", fmt.Errorf("Key object '%s' not found", key)
	}
}
func genScriptInit() string {
	role, _ := mInit("role")
	proc, _ := mInit("process")
	knb, _ := mInit("knowledge")
	lbl, _ := mInit("labels")
	cont, _ := mInit("contract")
	return fmt.Sprintf(`Action 'Init a microservice'()
			 Start
			  %s
			  %s
			  %s
			  %s
			  %s
			 Stop`, role, proc, knb, lbl, cont)
}
